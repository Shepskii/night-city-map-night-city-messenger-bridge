// Personalities write one general `signoffs` pool that covers these keys.
const SIGNOFF_ALIASES = {
  specialSignoffs: "signoffs",
  gigSignoffs: "signoffs",
  acceptanceSignoffs: "signoffs",
  completionNoticeSignoffs: "signoffs",
};

// Standard CPR Personality table entries, matched by a keyword so that
// slightly reworded or extended sheet text still resolves.
const PERSONALITY_KEYWORDS = [
  ["shy", "shy"],
  ["rebellious", "rebellious"],
  ["arrogant", "arrogant"],
  ["moody", "moody"],
  ["picky", "picky"],
  ["stable", "stable"],
  ["silly", "silly"],
  ["sneaky", "sneaky"],
  ["intellectual", "intellectual"],
  ["friendly", "friendly"],
];

export function resolvePersonality(text) {
  const value = String(text ?? "").toLowerCase();
  return PERSONALITY_KEYWORDS.find(([keyword]) => value.includes(keyword))?.[1] ?? null;
}

// Return the pool for `key` in a personality's voice, or the standard pool.
export function messagePool(key, personality = null) {
  const voice = PERSONALITY_POOLS[personality];
  const pool = voice?.[key] ?? voice?.[SIGNOFF_ALIASES[key]];
  return pool?.length ? pool : STANDARD_POOLS[key];
}

